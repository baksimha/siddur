export function translateNode(root) {
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (w.nextNode()) nodes.push(w.currentNode);
  for (const n of nodes) {
    const p = n.parentElement;
    if (!p || p.closest(SKIP)) continue;
    const raw = n.nodeValue;
    const t = raw.trim();
    if (!t || !/[א-ת]/.test(t)) continue;
    let r = D[t] || CITY_EN[t];
    if (!r) for (const [re, fn] of PATTERNS) { const m = t.match(re); if (m) { r = fn(m); if (r) break; } }
    if (r) n.nodeValue = raw.replace(t, r);
  }
  root.querySelectorAll('[placeholder]').forEach((el) => { const v = D[el.getAttribute('placeholder')]; if (v) el.setAttribute('placeholder', v); });
  root.querySelectorAll('[aria-label]').forEach((el) => { const v = D[el.getAttribute('aria-label')]; if (v) el.setAttribute('aria-label', v); });
  root.querySelectorAll('option').forEach((o) => { const v = D[o.textContent] || CITY_EN[o.textContent]; if (v) o.textContent = v; });
}

export function startTranslating(isEnglish) {
  let busy = false;
  const run = () => { if (!isEnglish() || busy) return; busy = true; try { translateNode(document.body); } finally { busy = false; } };
  new MutationObserver(run).observe(document.body, { childList: true, subtree: true, characterData: false });
  run();
}
